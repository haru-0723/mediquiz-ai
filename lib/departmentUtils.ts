export function getDepartmentType(department: string | null | undefined): 'medical' | 'pharmacy' | 'other' {
  const d = department ?? '';
  if (d.includes('医学') || d.includes('医師')) return 'medical';
  if (d.includes('薬学')) return 'pharmacy';
  return 'other';
}

